"""Upload storage, validation and text extraction.

Both the ``/upload`` endpoint and the ``send_email`` tool resolve files through
this module on purpose. An allowlist that exists in two places drifts, and the
one that matters most is the one guarding attachment reads: if ``/upload``
accepted a type that ``send_email`` then refused (or worse, the reverse), the
tool could be talked into reading a path the endpoint never validated.

Files are stored as ``uploads/<user_id>/<file_id><ext>`` with the caller's
original name kept in a ``<file_id>.meta.json`` sidecar. Encoding the id in the
filename means an attachment reference needs no server-side session: the id is
the whole lookup, so a send still resolves after a restart, and a caller cannot
address a file belonging to another user because the id is only ever looked up
inside its own directory.
"""

from __future__ import annotations

import json
import logging
import re
import shutil
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from backend.agent.config import get_settings

logger = logging.getLogger(__name__)


# -------------------------------------------------------------------------
# Limits
# -------------------------------------------------------------------------
#
# Storage limits and the email ceiling are different concerns and live in
# settings so they can be raised without a code change:
#
#   upload_max_file_mb / upload_max_files / upload_max_total_mb  -> storage
#   gmail_max_attachment_mb                                       -> one email
#
# Storage is generous on purpose. Gmail caps a message at 25 MB, so no email
# can carry an arbitrarily large attachment, but there is no reason to refuse
# storing a 200 MB scan — it simply cannot be mailed in one piece.


def _mb(value_mb: int) -> int:
    return int(value_mb) * 1024 * 1024


def max_file_bytes() -> int:
    return _mb(get_settings().upload_max_file_mb)


def max_files_per_request() -> int:
    return int(get_settings().upload_max_files)


def max_total_upload_bytes() -> int:
    return _mb(get_settings().upload_max_total_mb)


def max_total_attachment_bytes() -> int:
    """Ceiling for a single outgoing message."""

    return _mb(get_settings().gmail_max_attachment_mb)


#: How many rows a spreadsheet preview shows before it is truncated.
EXTRACT_ROW_LIMIT = 200

#: Characters of extracted text returned to the client for preview.
EXTRACT_CHAR_LIMIT = 20_000


# -------------------------------------------------------------------------
# Types
# -------------------------------------------------------------------------

#: Always refused, whatever else is allowed. These either execute on the
#: recipient's machine or are the usual first step of an attack chain, and no
#: legitimate reason to mail a file this app produced involves one.
BLOCKED_EXTS = frozenset({".exe", ".bat", ".sh", ".msi", ".js"})

MIME_BY_EXT: dict[str, str] = {
    ".pdf": "application/pdf",
    ".doc": "application/msword",
    ".docx": (
        "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
    ),
    ".txt": "text/plain",
    ".csv": "text/csv",
    ".xls": "application/vnd.ms-excel",
    ".xlsx": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    ".pptx": (
        "application/vnd.openxmlformats-officedocument.presentationml.presentation"
    ),
    ".jpg": "image/jpeg",
    ".jpeg": "image/jpeg",
    ".png": "image/png",
    ".webp": "image/webp",
}

ALLOWED_EXTS = frozenset(MIME_BY_EXT)

#: Coarse family used by the UI to pick a colour/icon per file.
CATEGORY_BY_EXT: dict[str, str] = {
    ".pdf": "pdf",
    ".doc": "word",
    ".docx": "word",
    ".txt": "text",
    ".csv": "excel",
    ".xls": "excel",
    ".xlsx": "excel",
    ".pptx": "powerpoint",
    ".jpg": "image",
    ".jpeg": "image",
    ".png": "image",
    ".webp": "image",
}

IMAGE_EXTS = frozenset({".jpg", ".jpeg", ".png", ".webp"})

# User ids become a directory name, so they are restricted to characters that
# cannot escape it. Anything else is rejected rather than escaped: a user id is
# generated by this app, and a caller sending "../.." is not one of them.
_SAFE_USER_ID = re.compile(r"^[A-Za-z0-9._-]{1,64}$")

_FILE_ID = re.compile(r"^[0-9a-f]{32}$")


class UploadError(ValueError):
    """A caller-supplied upload was rejected. Safe to show to the user."""


# -------------------------------------------------------------------------
# Paths
# -------------------------------------------------------------------------


def uploads_root() -> Path:
    """Repository-root ``uploads/``, created on demand."""

    root = Path(__file__).resolve().parents[2] / "uploads"
    root.mkdir(parents=True, exist_ok=True)
    return root


def user_upload_dir(user_id: str) -> Path:
    """Return ``uploads/<user_id>/``, rejecting any id that could escape it."""

    if not _SAFE_USER_ID.match(user_id or ""):
        raise UploadError(
            "Invalid user_id: only letters, digits, dot, dash and underscore "
            "are allowed."
        )

    if user_id in {".", ".."}:
        raise UploadError("Invalid user_id.")

    directory = (uploads_root() / user_id).resolve()

    # Belt and braces: even with the character filter above, confirm the
    # resolved directory is still inside uploads/.
    if uploads_root().resolve() not in directory.parents:
        raise UploadError("Invalid user_id.")

    directory.mkdir(parents=True, exist_ok=True)

    return directory


def extension_of(filename: str) -> str:
    return Path(filename or "").suffix.lower()


def validate_extension(filename: str) -> str:
    """Return the validated extension, or raise :class:`UploadError`."""

    ext = extension_of(filename)

    if not ext:
        raise UploadError(f"'{filename}' has no file extension.")

    # Checked before the allowlist so a blocked type is reported as blocked
    # rather than as a generic unsupported type.
    if ext in BLOCKED_EXTS:
        raise UploadError(
            f"'{ext}' files are never accepted ({filename})."
        )

    if ext not in ALLOWED_EXTS:
        allowed = ", ".join(sorted(ALLOWED_EXTS))
        raise UploadError(
            f"'{ext}' is not an allowed upload type. Allowed: {allowed}."
        )

    return ext


# -------------------------------------------------------------------------
# Text extraction
# -------------------------------------------------------------------------


def _extract_pdf(path: Path) -> str:
    from pypdf import PdfReader

    reader = PdfReader(str(path))
    pages = []

    for number, page in enumerate(reader.pages, start=1):
        text = page.extract_text() or ""
        pages.append(f"--- page {number} ---\n{text.strip()}")

    return "\n\n".join(pages)


def _extract_docx(path: Path) -> str:
    import docx

    document = docx.Document(str(path))
    parts = [p.text for p in document.paragraphs if p.text and p.text.strip()]

    for table in document.tables:
        for row in table.rows:
            cells = [c.text.strip() for c in row.cells]
            if any(cells):
                parts.append(" | ".join(cells))

    return "\n".join(parts)


def _extract_txt(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


def _extract_tabular(path: Path, ext: str) -> str:
    import pandas as pd

    if ext == ".csv":
        frame = pd.read_csv(str(path))
    elif ext == ".xlsx":
        frame = pd.read_excel(str(path), engine="openpyxl")
    else:  # .xls, via xlrd
        frame = pd.read_excel(str(path), engine="xlrd")

    truncated = len(frame) > EXTRACT_ROW_LIMIT
    view = frame.head(EXTRACT_ROW_LIMIT)

    text = view.to_string()

    if truncated:
        text += (
            f"\n\n[showing first {EXTRACT_ROW_LIMIT} of {len(frame)} rows]"
        )

    return text


def _extract_pptx(path: Path) -> str:
    from pptx import Presentation

    presentation = Presentation(str(path))
    slides = []

    for number, slide in enumerate(presentation.slides, start=1):
        chunks = []

        for shape in slide.shapes:
            if shape.has_text_frame:
                text = shape.text_frame.text.strip()
                if text:
                    chunks.append(text)

        if chunks:
            slides.append(f"--- slide {number} ---\n" + "\n".join(chunks))

    return "\n\n".join(slides)


def make_thumbnail(path: Path, file_id: str, user_id: str) -> str | None:
    """Write a small preview JPEG for an image upload.

    Returns the thumbnail's relative filename, or None when the image could not
    be decoded. A corrupt or non-image payload is reported rather than
    described: the alternative is inventing a description of a picture nobody
    looked at.
    """

    try:
        from PIL import Image
    except ImportError:  # pragma: no cover - Pillow is a hard requirement
        logger.warning("Pillow unavailable; skipping thumbnail")
        return None

    target_dir = user_upload_dir(user_id) / "thumbnails"
    target_dir.mkdir(parents=True, exist_ok=True)
    name = f"{file_id}.jpg"

    try:
        with Image.open(path) as image:
            image.thumbnail((320, 320))

            if image.mode not in ("RGB", "L"):
                # PNG transparency and palette modes have no direct JPEG
                # equivalent; flatten onto white rather than failing.
                image = image.convert("RGBA")
                flat = Image.new("RGB", image.size, (255, 255, 255))
                flat.paste(image, mask=image.split()[3])
                image = flat
            elif image.mode == "L":
                image = image.convert("RGB")

            image.save(target_dir / name, format="JPEG", quality=80)

        return f"thumbnails/{name}"

    except Exception as exc:  # noqa: BLE001 - any decode failure is non-fatal
        logger.warning("Thumbnail failed for %s: %s", path.name, exc)
        return None


def extract_text(path: Path, ext: str) -> tuple[str, str | None]:
    """Return ``(text, thumbnail_name)`` for an upload.

    Extraction failures are reported in the returned text rather than raised.
    A file that cannot be parsed is still perfectly sendable — refusing the
    upload because a PDF happens to be image-only would be worse than sending
    it without a text preview.
    """

    thumbnail: str | None = None

    try:
        if ext == ".pdf":
            return _extract_pdf(path), None
        if ext == ".docx":
            return _extract_docx(path), None
        if ext == ".txt":
            return _extract_txt(path), None
        if ext in {".csv", ".xls", ".xlsx"}:
            return _extract_tabular(path, ext), None
        if ext == ".pptx":
            return _extract_pptx(path), None

        if ext in IMAGE_EXTS:
            thumbnail = make_thumbnail(path, path.stem, _owner_of(path))
            # Deliberately no description. There is no vision model wired into
            # this path, and a caption invented from a filename would be a lie
            # the user could act on.
            return "Image ready to send. No text preview available.", thumbnail

        if ext == ".doc":
            return (
                "Legacy .doc file attached as-is. Text extraction is not "
                "supported for the old binary Word format; save it as .docx "
                "to get a preview.",
                None,
            )

    except Exception as exc:  # noqa: BLE001
        logger.warning("Text extraction failed for %s: %s", path.name, exc)
        return f"Attached as-is. Text could not be extracted ({exc}).", None

    return "Attached as-is.", None


