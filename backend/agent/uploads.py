@dataclass
class StoredFile:
    file_id: str
    original_name: str
    stored_name: str
    ext: str
    mime: str
    category: str
    size: int
    path: Path
    text: str = ""
    thumbnail: str | None = None
    meta: dict[str, Any] = field(default_factory=dict)

    def public(self) -> dict[str, Any]:
        return {
            "file_id": self.file_id,
            "name": self.original_name,
            "ext": self.ext,
            "mime": self.mime,
            "category": self.category,
            "size": self.size,
            "text_preview": self.text[:EXTRACT_CHAR_LIMIT],
            "thumbnail": self.thumbnail,
        }


_OWNERS: dict[str, str] = {}


def _owner_of(path: Path) -> str:
    return _OWNERS.get(path.stem, "default_user")


def store_upload(
    filename: str,
    source: Any,
    user_id: str,
) -> StoredFile:
    """Validate and persist one upload.

    ``source`` is anything with ``read()`` (a Starlette ``UploadFile`` works),
    which keeps this testable without constructing a request.
    """

    ext = validate_extension(filename)

    directory = user_upload_dir(user_id)

    file_id = uuid.uuid4().hex
    stored_name = f"{file_id}{ext}"
    destination = directory / stored_name

    written = 0
    cap = max_file_bytes()

    try:
        with destination.open("wb") as handle:
            while True:
                chunk = source.read(1024 * 256)

                if not chunk:
                    break

                written += len(chunk)

                # Enforced while streaming, not after: a 5 GB upload must be cut
                # off at the cap, not buffered first and measured afterwards.
                if written > cap:
                    raise UploadError(
                        f"'{filename}' exceeds the {cap // (1024 * 1024)} MB "
                        "per-file limit (upload_max_file_mb)."
                    )

                handle.write(chunk)

    except Exception:
        destination.unlink(missing_ok=True)
        raise

    if written == 0:
        destination.unlink(missing_ok=True)
        raise UploadError(f"'{filename}' is empty.")

    _OWNERS[file_id] = user_id

    text, thumbnail = extract_text(destination, ext)

    record = StoredFile(
        file_id=file_id,
        original_name=Path(filename).name[:255],
        stored_name=stored_name,
        ext=ext,
        mime=MIME_BY_EXT[ext],
        category=CATEGORY_BY_EXT[ext],
        size=written,
        path=destination,
        text=text,
        thumbnail=thumbnail,
    )

    (directory / f"{file_id}.meta.json").write_text(
        json.dumps(
            {
                "original_name": record.original_name,
                "ext": ext,
                "size": written,
                "uploaded_at": datetime.now(timezone.utc).isoformat(),
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    logger.info(
        "Stored upload %s (%s, %d bytes) for user %s",
        record.original_name, ext, written, user_id,
    )

    return record


def store_uploads(
    files: list[tuple[str, Any]],
    user_id: str,
) -> list[StoredFile]:
    """Persist a batch, enforcing the per-request count and size caps."""

    if not files:
        raise UploadError("No files were uploaded.")

    max_files = max_files_per_request()
    total_cap = max_total_upload_bytes()

    if len(files) > max_files:
        raise UploadError(
            f"At most {max_files} files per upload "
            f"(received {len(files)})."
        )

    _check_free_space()

    stored: list[StoredFile] = []
    total = 0

    try:
        for filename, source in files:
            record = store_upload(filename, source, user_id)
            total += record.size

            if total > total_cap:
                raise UploadError(
                    "Combined upload size exceeds the "
                    f"{total_cap // (1024 * 1024)} MB limit "
                    "(upload_max_total_mb)."
                )

            stored.append(record)

    except Exception:
        # All-or-nothing: leaving half a batch on disk would let a rejected
        # upload still be referenced by id afterwards.
        for record in stored:
            _delete_stored(record)
        raise

    return stored


def _delete_stored(record: StoredFile) -> None:
    record.path.unlink(missing_ok=True)

    meta = record.path.parent / f"{record.file_id}.meta.json"
    meta.unlink(missing_ok=True)

    thumbnail = record.path.parent / "thumbnails" / f"{record.file_id}.jpg"
    thumbnail.unlink(missing_ok=True)

    _OWNERS.pop(record.file_id, None)


# -------------------------------------------------------------------------
# Resolution for sending
# -------------------------------------------------------------------------


def resolve_attachments(
    user_id: str,
    file_ids: list[str],
) -> list[StoredFile]:
    """Resolve attachment ids to files inside this user's upload directory.

    Raises :class:`UploadError` for anything that is not a readable, allowed
    file already present in ``uploads/<user_id>/``.
    """

    if not file_ids:
        return []

    total_cap = max_total_attachment_bytes()

    directory = user_upload_dir(user_id)
    resolved: list[StoredFile] = []
    total = 0

    for file_id in file_ids:
        candidate = str(file_id or "").strip()

        if not _FILE_ID.match(candidate):
            raise UploadError(f"Invalid attachment id: {candidate!r}")

        matches = sorted(directory.glob(f"{candidate}.*"))

        # The sidecar shares the id, so drop it before looking for the payload.
        payload = [p for p in matches if not p.name.endswith(".meta.json")]

        if len(payload) != 1:
            raise UploadError(
                f"Attachment {candidate} was not found for this user."
            )

        path = payload[0]

        # The glob is built from a validated hex id and a fixed directory, so
        # this cannot escape — but the resolved path is checked anyway, because
        # this function reads a caller-supplied id.
        if path.resolve().parent != directory.resolve():
            raise UploadError(f"Attachment {candidate} is outside your uploads.")

        ext = extension_of(path.name)
        validate_extension(path.name)

        size = path.stat().st_size
        total += size

        if total > total_cap:
            raise UploadError(
                f"Attachments total {total / (1024 * 1024):.0f} MB, over the "
                f"{total_cap // (1024 * 1024)} MB that fits in one email. "
                "Gmail refuses messages above 25 MB, so send fewer files or "
                "raise gmail_max_attachment_mb (gmail will still cap it at "
                "25 MB)."
            )

        original_name = path.stem

        meta_path = directory / f"{candidate}.meta.json"
        if meta_path.exists():
            try:
                meta = json.loads(meta_path.read_text(encoding="utf-8"))
                original_name = meta.get("original_name") or original_name
            except (json.JSONDecodeError, OSError):
                logger.warning("Unreadable sidecar for %s", candidate)

        resolved.append(
            StoredFile(
                file_id=candidate,
                original_name=original_name,
                stored_name=path.name,
                ext=ext,
                mime=MIME_BY_EXT[ext],
                category=CATEGORY_BY_EXT[ext],
                size=size,
                path=path,
                # Recomputed rather than read from the sidecar: the thumbnail is
                # derivable from the id alone, and this path is reached on every
                # send as well as on preview requests.
                thumbnail=(
                    f"thumbnails/{candidate}.jpg"
                    if (directory / "thumbnails" / f"{candidate}.jpg").exists()
                    else None
                ),
            )
        )

    return resolved


def clear_user_uploads(user_id: str) -> None:
    """Remove everything belonging to one user. Used by tests."""

    shutil.rmtree(user_upload_dir(user_id), ignore_errors=True)


def _check_free_space() -> None:
    """Refuse new uploads when the disk is nearly full.

    The per-file cap alone still permits filling a volume, and a disk-full error
    part-way through a write leaves a truncated file that looks valid. Checking
    first turns that into an explanation.
    """

    required = _mb(get_settings().upload_min_free_mb)

    try:
        free = shutil.disk_usage(uploads_root()).free
    except OSError as exc:  # pragma: no cover - unusual filesystem failure
        logger.warning("Could not check free space: %s", exc)
        return

    if free < required:
        raise UploadError(
            f"Only {free / (1024 * 1024):.0f} MB free on disk; uploads need "
            f"{required // (1024 * 1024)} MB to spare. Free some space first."
        )


# -------------------------------------------------------------------------
# Async entry point
# -------------------------------------------------------------------------

#: Bytes buffered in memory before an upload spills to a temporary file.
SPOOL_MEMORY_LIMIT = 2 * 1024 * 1024


async def store_uploads_async(
    items: list[tuple[str, Any]],
    user_id: str,
) -> list[StoredFile]:
    """Spool async upload sources to disk, then store them.

    Starlette's ``UploadFile.read`` is a coroutine, so it cannot be handed to
    the synchronous writer. Each file is drained into a spooled temporary file
    first, with the per-file cap enforced *during* the drain — reading the whole
    body into memory and measuring afterwards would let a caller send a 2 GB
    request to be rejected only once it had already been buffered.
    """

    import tempfile

    if not items:
        raise UploadError("No files were uploaded.")

    max_files = max_files_per_request()
    cap = max_file_bytes()

    if len(items) > max_files:
        raise UploadError(
            f"At most {max_files} files per upload "
            f"(received {len(items)})."
        )

    _check_free_space()

    spooled: list[tuple[str, Any]] = []

    try:
        for filename, source in items:
            handle = tempfile.SpooledTemporaryFile(
                max_size=SPOOL_MEMORY_LIMIT, mode="w+b"
            )
            total = 0

            try:
                while True:
                    chunk = await source.read(256 * 1024)

                    if not chunk:
                        break

                    total += len(chunk)

                    if total > cap:
                        raise UploadError(
                            f"'{filename}' exceeds the "
                            f"{cap // (1024 * 1024)} MB per-file limit "
                            "(upload_max_file_mb)."
                        )

                    handle.write(chunk)

                handle.seek(0)

            except Exception:
                handle.close()
                raise

            spooled.append((filename, handle))

        return store_uploads(spooled, user_id)

    finally:
        for _, handle in spooled:
            try:
                handle.close()
            except Exception:  # noqa: BLE001
                pass